#!/usr/bin/env python3
"""Embed the boot-splash logo as a C++ byte array.

Reads the splash master PNG and writes a single translation unit defining
`splash::logoPng[]` / `splash::logoPngSize`, which
src/skel/amigaos/amiga_splash.cpp decodes in memory with lodepng. This keeps the
logo inside the executable -- the shipped game needs no external `splash/` file.

This module is the single source of truth for the master image path
(DEFAULT_PNG); both build drivers (build.py and build/amigaos/Makefile) obtain
it here, so they cannot drift.

Usage:
    gen_splash.py <output.cpp>              # uses DEFAULT_PNG
    gen_splash.py <input.png> <output.cpp>
    gen_splash.py --print-input             # print DEFAULT_PNG
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

# The splash master image, embedded into the binary at build time.
DEFAULT_PNG = os.path.join(ROOT, "splash", "PiStorm3D.png")


def generate(src, dst):
    """Write `src`'s bytes as `splash::logoPng` into `dst`; return the size."""
    with open(src, "rb") as f:
        data = f.read()
    if not data:
        raise ValueError("splash PNG is empty: %s" % src)

    # `extern` gives the arrays external linkage (a namespace-scope const would
    # otherwise be internal, and the renderer could not see it).
    with open(dst, "w") as f:
        f.write("// Generated by build/amigaos/gen_splash.py -- do not edit.\n")
        f.write("// Source: %s (%d bytes)\n" % (src, len(data)))
        f.write("namespace splash {\n")
        f.write("extern const unsigned char logoPng[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write("extern const unsigned int logoPngSize = %dU;\n" % len(data))
        f.write("} // namespace splash\n")
    return len(data)


def main(argv):
    if "--print-input" in argv[1:]:
        print(DEFAULT_PNG)
        return 0

    args = [a for a in argv[1:] if not a.startswith("-")]
    if len(args) == 1:
        src, dst = DEFAULT_PNG, args[0]
    elif len(args) == 2:
        src, dst = args
    else:
        sys.stderr.write("usage: gen_splash.py <output.cpp> | "
                         "<input.png> <output.cpp> | --print-input\n")
        return 2

    try:
        size = generate(src, dst)
    except (OSError, ValueError) as e:
        sys.stderr.write("gen_splash: %s\n" % e)
        return 1
    print("gen_splash: embedded %d bytes -> %s" % (size, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
