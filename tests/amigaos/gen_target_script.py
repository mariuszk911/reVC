#!/usr/bin/env python3
"""Generate the AmigaDOS `run_tests` script (and a JSON manifest) for the
target test harness.

The generated script is deliberately drive/path agnostic: it invokes the tests
and `serial_mark` by bare name, so the same drawer can be mounted on any
device (emulator or real HW). Run it with the test drawer as the current
directory, e.g.:

    CD DH11:
    Execute run_tests

(run_target.py issues the `CD` for you.)

The test list is supplied by the Makefile ($(C_TESTS) $(CXX_TESTS)), so it is
not duplicated here. For each test the source is scanned for its `<name>.log`
target, and a small per-test extra-argument table supplies fixtures.

Convention: a test's terminal line must be prefixed with the Makefile test name
("<name>: all ok" / "<name>: N failure(s)" / "<name>: SKIP ..."), because
run_target.py passes that name to parse_target_logs.py. The log *filename* may
differ (e.g. anglewrap_test -> anglewrap.log); the *prefix* must not.

Outputs:
  <out>       AmigaDOS script, executable as `Execute run_tests`
  <manifest>  JSON consumed by run_target.py: {"tests":[{"name","log","args"}]}
"""
import argparse
import json
import os
import re
import sys

# Any "....log" filename the test mentions; a device/path prefix (DH11:) or a
# directory is stripped so the manifest stores a drawer-relative name only.
LOG_RE = re.compile(r'"([^"]+\.log)"')
# Fixture arguments a test needs on the command line, drawer-relative.
EXTRA_ARGS = {
    "asset_endian_test": ["american.gxt"],
    "texture_decode_test": ["generic.txd"],
}


def find_source(src_dir, name):
    for ext in (".c", ".cpp"):
        path = os.path.join(src_dir, name + ext)
        if os.path.isfile(path):
            return path
    return None


def log_name_for(src_dir, name):
    path = find_source(src_dir, name)
    if path:
        try:
            with open(path, "r", errors="replace") as fh:
                m = LOG_RE.search(fh.read())
            if m:
                # Drop an Amiga device (DH11:) and any directory, leaving the
                # drawer-relative filename.
                return os.path.basename(m.group(1).split(":")[-1])
        except OSError:
            pass
    return name + ".log"


def build_manifest(src_dir, tests):
    entries = []
    for name in tests:
        entries.append({
            "name": name,
            "log": log_name_for(src_dir, name),
            "args": list(EXTRA_ARGS.get(name, [])),
        })
    return {"tests": entries}


def render_script(entries):
    lines = [
        "; Generated by tests/amigaos/gen_target_script.py - do not edit.",
        "; Run from the test drawer: CD <drawer>  then  Execute run_tests",
        "",
    ]
    for e in entries:
        begin = '"TARGET:BEGIN %s"' % e["name"]
        end = '"TARGET:END %s"' % e["name"]
        cmd = " ".join([e["name"]] + e["args"])
        lines.append("serial_mark %s" % begin)
        lines.append(cmd)
        lines.append("serial_mark %s" % end)
    lines.append("")
    lines.append('serial_mark "TARGET:ALLDONE"')
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, help="path of the run_tests script")
    ap.add_argument("--manifest", required=True, help="path of the JSON manifest")
    ap.add_argument("--src-dir", default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("tests", nargs="+", help="test names (no extension)")
    args = ap.parse_args(argv)

    manifest = build_manifest(args.src_dir, args.tests)
    script = render_script(manifest["tests"])

    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write(script)
    os.chmod(args.out, 0o777)
    with open(args.manifest, "w") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
